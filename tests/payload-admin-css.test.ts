import { describe, expect, test } from 'bun:test'

const GENERATED = 'src/styles/payload-admin-generated.css'
const HEADER = '/* Generated by scripts/assets/generate-payload-admin-css.ts. Do not edit by hand. */'

describe('payload admin generated css', () => {
  test('carries the generator header', async () => {
    const text = await Bun.file(GENERATED).text()
    expect(text.startsWith(HEADER)).toBe(true)
  })

  test('imports are sorted, unique, and resolve to real files', async () => {
    const text = await Bun.file(GENERATED).text()
    const specifiers = [...text.matchAll(/@import '([^']+)';/g)].map((m) => m[1] as string)
    expect(specifiers.length).toBeGreaterThan(0)
    expect([...specifiers].sort((a, b) => (a < b ? -1 : 1))).toEqual(specifiers)
    expect(new Set(specifiers).size).toBe(specifiers.length)
    for (const specifier of specifiers) {
      expect(specifier.startsWith('../../')).toBe(true)
      expect(await Bun.file(`src/styles/${specifier}`).exists()).toBe(true)
    }
  })

  test('excludes the double-inlined styles.css, includes app.css', async () => {
    const text = await Bun.file(GENERATED).text()
    expect(text).not.toContain('dist/styles.css')
    expect(text).toContain('@payloadcms/ui/dist/css/app.css')
  })

  test('regeneration is a no-op (byte-stable output)', async () => {
    const before = await Bun.file(GENERATED).arrayBuffer()
    await Bun.$`bun run scripts/assets/generate-payload-admin-css.ts`.quiet()
    const after = await Bun.file(GENERATED).arrayBuffer()
    expect(Buffer.from(after).equals(Buffer.from(before))).toBe(true)
  })
})
